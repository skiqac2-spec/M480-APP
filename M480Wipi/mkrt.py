# pack compiled runtime classes into an embedded zip (src/rt_jar.c)
import sys, os, zipfile, io
root = sys.argv[1]
buf = io.BytesIO()
with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for d, _, fs in os.walk(root):
        for f in sorted(fs):
            if f.endswith('.class'):
                p = os.path.join(d, f)
                z.write(p, os.path.relpath(p, root).replace(os.sep, '/'))
data = buf.getvalue()
with open(sys.argv[2], 'w') as o:
    o.write('/* generated by tools_mkrt.py - runtime class library */\n#include "types.h"\n')
    o.write('const u32 rt_jar_len = %d;\nconst u8 rt_jar[] = {\n' % len(data))
    for i in range(0, len(data), 24):
        o.write(','.join(str(b) for b in data[i:i+24]) + ',\n')
    o.write('};\n')
print(len(data), 'bytes')
